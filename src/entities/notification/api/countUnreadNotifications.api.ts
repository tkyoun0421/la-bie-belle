import type { DB } from "@/shared/api/database";

export async function countUnreadNotifications(client: DB): Promise<number> {
  const { count, error } = await client
    .from("notifications")
    .select("id", { count: "exact", head: true })
    .is("read_at", null);

  if (error) {
    throw error;
  }

  return count ?? 0;
}
